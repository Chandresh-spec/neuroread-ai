export function getDocumentContent(item) {
  if (!item) return defaultSampleDocument;
  if (item.paragraphs && item.paragraphs.length > 0) {
    return {
      title: item.title || defaultSampleDocument.title,
      author: item.author || 'NeuroRead Library',
      readTime: item.readTime || '3 min read',
      progress: item.progressPercent || 100,
      paragraphs: item.paragraphs,
      simplified: item.simplified || defaultSampleDocument.simplified,
      structured: item.structured || defaultSampleDocument.structured,
    };
  }
  const key = item.id;
  if (key && readerDocuments[key]) {
    return readerDocuments[key];
  }
  const title = item.title || item.name || defaultSampleDocument.title;
  const author = item.author || (item.format ? `Uploaded ${item.format.toUpperCase()} Document` : 'NeuroRead Library');
  return {
    title,
    author,
    readTime: item.duration || '3 min read',
    progress: item.progressPercent || 100,
    paragraphs: [
      `Welcome to "${title}". This distraction-free reading view adapts automatically to your cognitive preferences, spacing controls, and contrast theme.`,
      ...defaultSampleDocument.paragraphs.slice(1),
    ],
    simplified: defaultSampleDocument.simplified,
    structured: defaultSampleDocument.structured,
  };
}

